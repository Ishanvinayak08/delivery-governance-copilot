"""Markdown / CSV / JSON outputs. Every artefact is labelled DRAFT until a PM approves it."""
from __future__ import annotations

import csv
import json
from datetime import date
from pathlib import Path

from dgc.models import Finding, RaidItem

BANNER = ("> **DRAFT: generated by Delivery Governance Copilot. Not approved. "
          "A named project manager must review before this is shared.**")
ICON = {"RED": "RED", "AMBER": "AMBER", "GREEN": "GREEN"}


def _cell(s: object) -> str:
    return str(s if s not in (None, "") else "-").replace("|", "/").replace("\n", " ")


def _table(headers: list[str], rows: list[list]) -> str:
    if not rows:
        return "_None._\n"
    lines = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    lines += ["| " + " | ".join(_cell(c) for c in r) + " |" for r in rows]
    return "\n".join(lines) + "\n"


def build_report(project: str, as_of: date, items: list[RaidItem], findings: list[Finding],
                 rag: str, rag_reason: str, sources: list[dict], mode_note: str) -> str:
    open_items = [i for i in items if i.is_open]
    by_type = {t: sum(1 for i in open_items if i.item_type == t)
               for t in ("Risk", "Issue", "Dependency", "Action", "Assumption")}
    counts = {s: sum(1 for f in findings if f.severity == s) for s in ("Critical", "High", "Medium", "Low")}
    decisions = [i for i in items if i.item_type == "Decision"]
    review = [i for i in items if i.confidence < 0.7 and i.source_kind != "jira"]

    parts = [f"# {project}: Weekly Delivery Governance Report", f"**As of:** {as_of.isoformat()}  ",
             f"**Overall governance RAG:** {ICON[rag]}: {rag_reason}", "", BANNER, "",
             "## 1. Summary", "",
             f"- Open items: {len(open_items)} "
             f"(Risks {by_type['Risk']}, Issues {by_type['Issue']}, Dependencies {by_type['Dependency']}, "
             f"Actions {by_type['Action']}, Assumptions {by_type['Assumption']})",
             f"- Governance findings: {counts['Critical']} critical, {counts['High']} high, "
             f"{counts['Medium']} medium, {counts['Low']} low",
             f"- Extraction mode: {mode_note}", "",
             "## 2. Escalations and findings requiring PM attention", "",
             _table(["Sev", "Rule", "Item", "Title", "Finding", "Recommended action"],
                    [[f.severity, f.rule_id, f.item_id, f.item_title, f.message, f.recommendation]
                     for f in findings if f.severity in ("Critical", "High")]),
             "## 3. Other findings", "",
             _table(["Sev", "Rule", "Item", "Title", "Finding"],
                    [[f.severity, f.rule_id, f.item_id, f.item_title, f.message]
                     for f in findings if f.severity in ("Medium", "Low")]),
             "## 4. Open RAID items", "",
             _table(["ID", "Type", "Title", "Owner", "Due", "Severity", "Status", "Source"],
                    [[i.item_id, i.item_type, i.title, i.owner, i.due.isoformat() if i.due else "",
                      i.severity, i.status, i.external_key or i.source]
                     for i in sorted(open_items, key=lambda x: (x.item_type, x.item_id))]),
             "## 5. Decisions recorded", "",
             _table(["ID", "Decision", "Source"], [[d.item_id, d.title, d.source] for d in decisions]),
             "## 6. Items needing human review (low extraction confidence)", "",
             _table(["ID", "Type", "Title", "Confidence", "Source"],
                    [[i.item_id, i.item_type, i.title, i.confidence, i.source] for i in review]),
             "## 7. Traceability", "",
             _table(["Input", "Kind", "SHA-256"], [[s["path"], s["kind"], s["sha256"][:16] + "..."] for s in sources])]
    return "\n".join(parts)


def write_outputs(out_dir: Path, report_md: str, items: list[RaidItem], findings: list[Finding]) -> dict:
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    paths = {"report": out_dir / "weekly_status_report.md", "raid": out_dir / "raid_log.csv",
             "findings": out_dir / "governance_findings.json"}
    paths["report"].write_text(report_md, encoding="utf-8")
    rows = [i.to_row() for i in items]
    fields = ["item_id", "item_type", "title", "owner", "due", "severity", "status", "source",
              "source_kind", "external_key", "updated", "confidence"]
    with open(paths["raid"], "w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=fields, extrasaction="ignore")
        w.writeheader()
        w.writerows(rows)
    paths["findings"].write_text(json.dumps([f.to_dict() for f in findings], indent=2), encoding="utf-8")
    return paths
